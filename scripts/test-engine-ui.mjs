import { _electron } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

const root=process.cwd();
const base=path.join(root,'.test-data',`engine-ui-${Date.now()}`);
const fixture=path.join(base,'app-without-pi');
const data=path.join(base,'data');
const download=path.join(base,'用户选择的保存位置');
fs.mkdirSync(fixture,{recursive:true});fs.mkdirSync(download,{recursive:true});
fs.writeFileSync(path.join(download,'keep.txt'),'existing user file');
const copyDirectory=(source,target)=>{fs.mkdirSync(target,{recursive:true});for(const item of fs.readdirSync(source,{withFileTypes:true})){const from=path.join(source,item.name),to=path.join(target,item.name);item.isDirectory()?copyDirectory(from,to):fs.copyFileSync(from,to);}};
for(const name of ['dist','dist-electron','extensions'])copyDirectory(path.join(root,name),path.join(fixture,name));
fs.copyFileSync(path.join(root,'package.json'),path.join(fixture,'package.json'));
// Keep the download component while deliberately omitting Pi itself.
fs.mkdirSync(path.join(fixture,'runtime/node_modules'),{recursive:true});
fs.symlinkSync(path.join(root,'runtime/node_modules/npm'),path.join(fixture,'runtime/node_modules/npm'),'junction');
let app;const errors=[];const results=[];
const snapshot=page=>page.evaluate(()=>window.saint.invoke('bootstrap'));
const waitState=async(page,predicate,timeout=45000)=>{const end=Date.now()+timeout;while(Date.now()<end){const state=await snapshot(page);if(predicate(state))return state;await page.waitForTimeout(100);}throw new Error('Timed out waiting for Pi state');};
const choose=async(folder,cancel=false)=>app.evaluate(({dialog},{folder,cancel})=>{dialog.showOpenDialog=async(_window,options)=>{globalThis.lastEnginePicker=options;return {canceled:cancel,filePaths:cancel?[]:[folder]};};},{folder,cancel});
try {
  app=await _electron.launch({args:[fixture],env:{...process.env,SAINT_DATA_DIR:data}});
  const page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));
  await page.getByRole('button',{name:'管理与添加引擎'}).click();
  await waitState(page,d=>!d.engine.installed&&!d.engine.updating);
  await page.getByRole('button',{name:'下载并连接 Pi',exact:true}).waitFor();
  fs.mkdirSync('artifacts',{recursive:true});await page.screenshot({path:'artifacts/engine-missing.png',animations:'disabled'});
  await choose(download,true);await page.getByRole('button',{name:'下载并连接 Pi',exact:true}).click();
  assert.deepEqual(fs.readdirSync(download),['keep.txt']);assert.equal((await snapshot(page)).engine.installed,false);
  const picker=await app.evaluate(()=>globalThis.lastEnginePicker);assert.equal(picker.title,'选择 Pi 保存位置');assert.ok(picker.properties.includes('openDirectory'));
  results.push('missing Pi detected; download picker cancellation changed no files or selection');
  await choose(download);await page.getByRole('button',{name:'下载并连接 Pi',exact:true}).click();
  const installed=await waitState(page,d=>d.engine.installed&&!d.engine.updating&&d.snapshot.connected,240000);
  assert.ok(installed.engine.path.startsWith(download+path.sep));assert.equal(fs.readFileSync(path.join(download,'keep.txt'),'utf8'),'existing user file');
  assert.equal(installed.threads.length,0);assert.equal(installed.snapshot.threadId,undefined);
  assert.ok(installed.snapshot.commands.some(c=>c.name==='saint-access'));
  assert.equal(JSON.parse(fs.readFileSync(path.join(data,'workspace.json'),'utf8')).runtimeInstallDirectory,download);
  await page.screenshot({path:'artifacts/engine-installed.png',animations:'disabled'});
  results.push('actual npm download into selected Chinese directory; verified live Pi RPC without creating a project');
  const persisted=fs.readFileSync(path.join(data,'workspace.json'),'utf8');
  const empty=path.join(base,'not-pi');fs.mkdirSync(empty);
  await choose(empty);await page.getByRole('button',{name:'连接已下载的 Pi',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'没有找到可运行的 Pi'}).waitFor();
  assert.equal(fs.readFileSync(path.join(data,'workspace.json'),'utf8'),persisted);assert.equal((await snapshot(page)).snapshot.connected,true);
  results.push('invalid folder leaves existing live engine and saved selection intact');
  await choose(path.join(root,'runtime'));await page.getByRole('button',{name:'连接已下载的 Pi',exact:true}).click();
  await waitState(page,d=>d.engine.external&&!d.engine.updating&&d.snapshot.connected);
  await page.getByText('如何连接本地已下载的 Pi',{exact:true}).click();await page.getByText('npm root -g',{exact:true}).waitFor();
  const cli=(await snapshot(page)).engine.path;await choose(cli);await page.getByRole('button',{name:'选择入口文件',exact:true}).click();
  await waitState(page,d=>!d.engine.updating&&d.snapshot.connected&&d.engine.path===cli);
  await page.screenshot({path:'artifacts/engine-local-guide.png',animations:'disabled'});
  results.push('existing install folder and CLI entry both connect; embedded local setup guide is available');
  await app.close();app=undefined;
  app=await _electron.launch({args:[fixture],env:{...process.env,SAINT_DATA_DIR:data}});
  const reopened=await app.firstWindow();await waitState(reopened,d=>d.snapshot.connected&&!d.snapshot.busy);
  assert.equal((await snapshot(reopened)).engine.path,cli);results.push('selected local engine reconnects after restart without a project');
  assert.deepEqual(errors,[]);
  fs.writeFileSync('artifacts/engine-test.json',JSON.stringify({date:new Date().toISOString(),results,pi:installed.engine.current},null,2));
  console.log(JSON.stringify({passed:results},null,2));
} finally {if(app)await app.close();}
